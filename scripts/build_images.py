#!/usr/bin/env python3
"""
Builds web-ready images for the site.

Reads every image in  source-images/  (jpg, jpeg, png or webp) and writes:
  - assets/img/art/<name>-<width>.webp   resized copies for phones, laptops and big screens
  - assets/js/images.js                  sizes, colours and tiny blurred previews for the site
  - assets/img/og.jpg                    the preview image shown when the link is shared

The file name (without extension) is the key used in assets/js/data.js,
e.g. source-images/wait-and-pray.png  ->  image: "wait-and-pray"

Usage (from the project folder):
    pip install pillow
    python3 scripts/build_images.py
"""

import base64
import io
import json
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "source-images"
OUT = ROOT / "assets" / "img" / "art"
MANIFEST = ROOT / "assets" / "js" / "images.js"
OG = ROOT / "assets" / "img" / "og.jpg"

WIDTHS = [480, 960, 1600, 2400]
QUALITY = 82
PAPER = (244, 239, 231)  # page background, used behind transparent PNGs
OG_PICKS = ["iyawo-rere", "ore-iyawo", "the-enlightenment"]


def load(path):
    im = Image.open(path)
    im = ImageOps.exif_transpose(im)
    if im.mode in ("RGBA", "LA", "P"):
        im = im.convert("RGBA")
        bg = Image.new("RGB", im.size, PAPER)
        bg.paste(im, mask=im.split()[-1])
        return bg
    return im.convert("RGB")


def widths_for(w):
    out = [x for x in WIDTHS if x < w * 0.85]  # skip a size too close to the original
    out.append(min(w, WIDTHS[-1]))
    return out


def average_colour(im):
    r, g, b = im.resize((1, 1), Image.Resampling.BOX).getpixel((0, 0))
    return f"#{r:02x}{g:02x}{b:02x}"


def lqip(im):
    small = im.copy()
    small.thumbnail((24, 24), Image.Resampling.LANCZOS)
    buf = io.BytesIO()
    small.save(buf, "WEBP", quality=50)
    return "data:image/webp;base64," + base64.b64encode(buf.getvalue()).decode()


def build_og(images):
    W, H, pad, gap = 1200, 630, 70, 36
    canvas = Image.new("RGB", (W, H), PAPER)
    picks = [images[k] for k in OG_PICKS if k in images]
    if not picks:
        picks = list(images.values())[:3]
    h = H - pad * 2
    scaled = [im.resize((round(im.width * h / im.height), h), Image.Resampling.LANCZOS) for im in picks]
    total = sum(s.width for s in scaled) + gap * (len(scaled) - 1)
    if total > W - pad * 2:
        f = (W - pad * 2) / total
        scaled = [s.resize((round(s.width * f), round(s.height * f)), Image.Resampling.LANCZOS) for s in scaled]
        total = sum(s.width for s in scaled) + gap * (len(scaled) - 1)
    x = (W - total) // 2
    for s in scaled:
        canvas.paste(s, (x, (H - s.height) // 2))
        x += s.width + gap
    canvas.save(OG, "JPEG", quality=86, optimize=True, progressive=True)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.webp"):
        old.unlink()

    manifest, loaded = {}, {}
    files = sorted(p for p in SRC.iterdir() if p.suffix.lower() in (".jpg", ".jpeg", ".png", ".webp"))
    for path in files:
        key = path.stem
        im = load(path)
        loaded[key] = im
        srcset = []
        for w in widths_for(im.width):
            h = round(im.height * w / im.width)
            resized = im if w == im.width else im.resize((w, h), Image.Resampling.LANCZOS)
            name = f"{key}-{w}.webp"
            resized.save(OUT / name, "WEBP", quality=QUALITY, method=6)
            srcset.append([f"assets/img/art/{name}", w])
        manifest[key] = {
            "w": im.width,
            "h": im.height,
            "color": average_colour(im),
            "lqip": lqip(im),
            "srcset": srcset,
        }
        print(f"  {key:32s} {im.width}x{im.height}  ->  {len(srcset)} sizes")

    MANIFEST.write_text(
        "/* Generated by scripts/build_images.py. Do not edit by hand. */\n"
        "window.IMAGES = " + json.dumps(manifest, indent=1) + ";\n",
        encoding="utf-8",
    )
    build_og(loaded)
    print(f"\nWrote {len(manifest)} images, {MANIFEST.relative_to(ROOT)} and {OG.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
